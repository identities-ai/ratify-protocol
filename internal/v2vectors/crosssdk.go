// VerifyCrossSDK checks a cross-SDK fixture with the Go reference: key
// derivation, required coverage, strict decode and byte-identical re-encode,
// each signature transcript, and every object's verify procedure. The root
// package conformance test additionally reproduces every digest.
func VerifyCrossSDK(data []byte) (err error) {
	var f crossSDKFile
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&f); err != nil {
		return fmt.Errorf("decode: %w", err)
	}
	if f.Version != 2 || f.SDK == "" || f.SDKVersion == "" || f.Generator == "" {
		return fmt.Errorf("version, sdk, sdk_version and generator are required")
	}
	keys := map[string]ratify.HybridPublicKey{}
	privs := map[string]ratify.HybridPrivateKey{}
	ids := map[string]string{}
	for _, k := range f.Keys {
		var ed, ml [32]byte
		edSeed, err1 := hex.DecodeString(k.Ed25519SeedHex)
		mlSeed, err2 := hex.DecodeString(k.MLDSA65SeedHex)
		if err1 != nil || err2 != nil || len(edSeed) != 32 || len(mlSeed) != 32 {
			return fmt.Errorf("key %s: bad seed", k.Name)
		}
		copy(ed[:], edSeed)
		copy(ml[:], mlSeed)
		pub, priv, err := ratify.HybridKeypairFromSeeds(ed, ml)
		if err != nil {
			return fmt.Errorf("key %s: %w", k.Name, err)
		}
		if k.PublicKey["ed25519"] != b64(pub.Ed25519) || k.PublicKey["ml_dsa_65"] != b64(pub.MLDSA65) {
			return fmt.Errorf("key %s: seeds do not derive the public key", k.Name)
		}
		if keyIDV2(pub) != k.KeyIDV2 {
			return fmt.Errorf("key %s: key_id_v2 differs", k.Name)
		}
		if _, dup := keys[k.Name]; dup {
			return fmt.Errorf("key %s: duplicate name", k.Name)
		}
		keys[k.Name], privs[k.Name], ids[k.Name] = pub, priv, k.KeyIDV2
	}
	for _, name := range CrossSDKKeyNames {
		if _, ok := keys[name]; !ok {
			return fmt.Errorf("missing key %s", name)
		}
	}
	err = catch(func() {
		seenKinds, seenCodes := map[string]bool{}, map[int]bool{}
		for _, o := range f.Objects {
			seenKinds[o.Kind] = true
			if e := verifyCrossObject(o, keys, ids, seenCodes); e != nil {
				panic(fmt.Sprintf("%s: %v", o.Name, e))
			}
		}
		for _, kind := range CrossSDKKinds {
			if !seenKinds[kind] {
				panic("no " + kind + " object")
			}
		}
		for code := 1; code <= 9; code++ {
			if !seenCodes[code] {
				panic(fmt.Sprintf("no signature for object_type_code %d", code))
			}
		}
		if !crossCoverage(f.Objects) {
			panic("no delegation certificate with every registered constraint type and an extension type, or no receipt with constraint_evaluators")
		}
		if f.ScenarioConfiguration == nil || len(f.Scenarios) == 0 {
			panic("no verifier and release scenarios")
		}
		if e := checkCrossScenarios(*f.ScenarioConfiguration, f.Scenarios, keys, privs[f.ScenarioConfiguration.VerifierKey]); e != nil {
			panic(e.Error())
		}
	})
	return err
}

func crossCoverage(objects []objectVector) bool {
	var constraints, evaluators bool
	for _, o := range objects {
		wire := must(b64d(o.WireB64))
		switch o.Kind {
		case "delegation_certificate":
			c := must(ratify.DecodeDelegationCertV2(wire))
			types, extension := map[ratify.ConstraintType]bool{}, false
			for _, k := range c.Constraints {
				types[k.Type] = true
				extension = extension || !ratify.IsRegisteredConstraintTypeV2(k.Type)
			}
			all := extension
			for _, t := range []ratify.ConstraintType{ratify.ConstraintMaxRate, ratify.ConstraintReceiverAudience, ratify.ConstraintResourcePath, ratify.ConstraintTimeWindow, ratify.ConstraintMaxAmount} {
				all = all && types[t]
			}
			constraints = constraints || all
		case "verification_receipt":
			evaluators = evaluators || len(must(ratify.DecodeVerificationReceiptV2(wire)).ConstraintEvaluators) > 0
		}
	}
	return constraints && evaluators
}

func reencode(kind string, wire []byte) ([]byte, error) {
	switch kind {
	case "delegation_certificate":
		v, err := ratify.DecodeDelegationCertV2(wire)
		if err != nil {
			return nil, err
		}
		return ratify.EncodeDelegationCertV2(v)
	case "proof_bundle":
		v, err := ratify.DecodeProofBundleV2(wire)
		if err != nil {
			return nil, err
		}
		return ratify.EncodeProofBundleV2(v)
	case "revocation_list":
		v, err := ratify.DecodeRevocationListV2(wire)
		if err != nil {
			return nil, err
		}
		return ratify.EncodeRevocationListV2(v)
	case "revocation_push":
		v, err := ratify.DecodeRevocationPushV2(wire)
		if err != nil {
			return nil, err
		}
		return ratify.EncodeRevocationPushV2(v)
	case "key_rotation_statement":
		v, err := ratify.DecodeKeyRotationStatementV2(wire)
		if err != nil {
			return nil, err
		}
		return ratify.EncodeKeyRotationStatementV2(v)
	case "witness_entry":
		v, err := ratify.DecodeWitnessEntryV2(wire)
		if err != nil {
			return nil, err
		}
		return ratify.EncodeWitnessEntryV2(v)
	case "transaction_receipt":
		v, err := ratify.DecodeTransactionReceiptV2(wire)
		if err != nil {
			return nil, err
		}
		return ratify.EncodeTransactionReceiptV2(v)
	case "verification_receipt", "receipt_bundle_binding":
		v, err := ratify.DecodeVerificationReceiptV2(wire)
		if err != nil {
			return nil, err
		}
		return ratify.EncodeVerificationReceiptV2(v)
	}
	return nil, fmt.Errorf("unknown kind %q", kind)
}

func verifyCrossObject(o objectVector, keys map[string]ratify.HybridPublicKey, ids map[string]string, seenCodes map[int]bool) error {
	wire, err := b64d(o.WireB64)
	if err != nil {
		return err
	}
	if got, err := reencode(o.Kind, wire); err != nil || !bytes.Equal(got, wire) {
		return fmt.Errorf("re-encoding is not byte-identical (%v)", err)
	}
	if err := verifyCrossKind(o, wire, keys); err != nil {
		return fmt.Errorf("verify: %w", err)
	}
	for _, s := range o.Signatures {
		seenCodes[s.ObjectTypeCode] = true
		signable := projection(wire, s.Field)
		if b64(signable) != s.SignableB64 || hex.EncodeToString(sha384(signable)) != s.SignableSHA384 {
			return fmt.Errorf("%s: signable projection differs", s.Field)
		}
		code := uint16(s.ObjectTypeCode)
		m := message(code, signable)
		pub, ok := keys[s.Signer]
		if !ok || ids[s.Signer] != s.SignerKeyIDV2 {
			return fmt.Errorf("%s: unknown signer or key ID %s", s.Field, s.Signer)
		}
		tr, mu := externalMu(pub.MLDSA65, code, m)
		if b64(m) != s.MessageB64 || s.MLDSAContext != string(mldsaContext(code)) || b64(tr) != s.MLDSATrB64 || b64(mu) != s.MLDSAMuB64 {
			return fmt.Errorf("%s: transcript differs", s.Field)
		}
		for _, component := range []string{"ed25519", "ml_dsa_65"} {
			v, _ := s.Signature[component].(string)
			if v == "" || !bytes.Contains(wire, []byte(strconv.Quote(v))) {
				return fmt.Errorf("%s: pinned %s signature is not carried by the wire object", s.Field, component)
			}
		}
	}
	return nil
}

// projection is the SPEC-v2 §5 signable projection for one signature field.
func projection(wire []byte, field string) []byte {
	switch {
	case field == "signature":
		return without(wire, "signature")
	case field == "challenge_sig":
		return without(wire, "delegations", "challenge_sig")
	case field == "old_signature" || field == "new_signature":
		return without(wire, "old_signature", "new_signature")
	case strings.HasPrefix(field, "delegations["):
		i := must(strconv.Atoi(strings.TrimSuffix(strings.TrimPrefix(field, "delegations["), "].signature")))
		return without(canon(arr(obj(parse(wire))["delegations"])[i]), "signature")
	case strings.HasPrefix(field, "party_signatures["):
		return must(ratify.TransactionReceiptV2SignBytes(must(ratify.DecodeTransactionReceiptV2(wire))))
	}
	panic("unknown signature field " + field)
}

func verifyCrossKind(o objectVector, wire []byte, keys map[string]ratify.HybridPublicKey) error {
	vc := o.Verify
	switch o.Kind {
	case "delegation_certificate":
		return ratify.VerifyDelegationCertV2Signature(must(ratify.DecodeDelegationCertV2(wire)))
	case "proof_bundle":
		return ratify.VerifyProofBundleV2Signatures(must(ratify.DecodeProofBundleV2(wire)))
	case "revocation_list":
		return ratify.VerifyRevocationListV2Signature(must(ratify.DecodeRevocationListV2(wire)), vc.BoundIssuerID, keys[vc.StatusKey])
	case "revocation_push":
		return ratify.VerifyRevocationPushV2Signature(must(ratify.DecodeRevocationPushV2(wire)), vc.BoundIssuerID, keys[vc.StatusKey])
	case "key_rotation_statement":
		s := vc.RotationState
		state := ratify.KeyRotationV2State{AuthorityID: s.AuthorityID, RecoveryEpoch: s.RecoveryEpoch, Role: s.Role, Sequence: s.Sequence,
			HeadHash: must(b64d(s.HeadHashB64)), CurrentKey: keys[s.CurrentKey], UsedKeyIDs: s.UsedKeyIDs}
		return ratify.VerifyKeyRotationStatementV2(must(ratify.DecodeKeyRotationStatementV2(wire)), state, vc.Now, vc.FutureSkew)
	case "witness_entry":
		_, err := ratify.VerifyWitnessEntryV2(must(ratify.DecodeWitnessEntryV2(wire)), witnessHead(vc.Head), keys[vc.WitnessKey])
		return err
	case "transaction_receipt":
		return ratify.VerifyTransactionReceiptV2Signatures(must(ratify.DecodeTransactionReceiptV2(wire)))
	case "verification_receipt":
		w := witnessHead(vc.Head)
		head := ratify.ReceiptV2Head{LogID: w.LogID, VerifierID: vc.Head.VerifierID, Sequence: w.Sequence, HeadHash: w.HeadHash, AcceptedDigests: w.AcceptedDigests, Frozen: w.Frozen}
		_, err := ratify.VerifyVerificationReceiptV2(must(ratify.DecodeVerificationReceiptV2(wire)), keys[vc.VerifierKey], head)
		return err
	case "receipt_bundle_binding":
		bundle, err := ratify.DecodeProofBundleV2(must(b64d(o.BundleB64)))
		if err != nil {
			return err
		}
		return ratify.CheckVerificationReceiptV2BundleBinding(must(ratify.DecodeVerificationReceiptV2(wire)), bundle)
	}
	return fmt.Errorf("unknown kind %q", o.Kind)
}

func witnessHead(h *HeadJSON) ratify.WitnessV2Head {
	head := ratify.WitnessV2Head{LogID: h.LogID, Sequence: h.Sequence, HeadHash: must(b64d(h.HeadHashB64)), AcceptedDigests: map[int64][]byte{}, Frozen: h.Frozen}
	for seq, d := range h.AcceptedDigests {
		head.AcceptedDigests[must(strconv.ParseInt(seq, 10, 64))] = must(b64d(d))
	}
	return head
}
