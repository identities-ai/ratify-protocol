// Cross-SDK fixtures (SPEC-v2 §8.1). Every SDK writes
// testvectors/v2/cross-sdk/<sdk>.json from freshly generated keys and hedged
// ML-DSA-65 signatures, and every other SDK verifies it with its objects.json
// code path. The file layout is documented in testvectors/v2/README.md.

// CrossSDKDir is the cross-SDK fixture directory relative to testvectors/v2.
const CrossSDKDir = "cross-sdk"

// CrossSDKKeyNames are the key names every cross-SDK fixture defines. Verify
// contexts and signature records refer to keys by these names.
var CrossSDKKeyNames = []string{
	"root", "intermediate", "agent", "verifier", "status_root", "status_intermediate",
	"witness", "party_b_root", "party_b_agent", "rotation_genesis", "rotation_second",
}

// CrossSDKKinds are the object kinds every cross-SDK fixture contains at least
// once. receipt_bundle_binding pairs a verification receipt (wire_b64) with the
// proof bundle it was issued for (bundle_b64).
var CrossSDKKinds = []string{
	"delegation_certificate", "proof_bundle", "revocation_list", "revocation_push", "key_rotation_statement",
	"witness_entry", "transaction_receipt", "verification_receipt", "receipt_bundle_binding",
}

type crossSDKFile struct {
	Version     int            `json:"version"`
	Description string         `json:"description"`
	SDK         string         `json:"sdk"`
	SDKVersion  string         `json:"sdk_version"`
	Generator   string         `json:"generator"`
	Kinds       map[string]int `json:"kind_object_type_codes"`
	Keys        []keyEntry     `json:"keys"`
	Objects     []objectVector `json:"objects"`
	// ScenarioConfiguration and Scenarios are the verifier and release
	// scenarios of SPEC-v2 §8.1 (crosssdk_scenarios.go).
	ScenarioConfiguration *crossScenarioConfigJSON `json:"scenario_configuration"`
	Scenarios             []crossScenarioJSON      `json:"scenarios"`
}

const crossSDKDescription = "Cross-SDK fixture (SPEC-v2 §8.1). keys are freshly generated by the producing SDK (keys.json entry schema; seeds are throwaway test data). objects follow the objects.json object schema: every ML-DSA-65 component is hedged, so signature bytes are not reproducible. A verifying SDK MUST derive each public key and key_id_v2 from its seeds, and for every object decode wire_b64, re-encode it to identical bytes, derive each signable projection, transcript M, context, tr and mu, find each pinned signature in the wire object, verify every signature with the named verify context (key names resolve to this file's keys), and reproduce every digest. A receipt_bundle_binding object is verified by strict decode of wire_b64 (verification receipt) and bundle_b64 (proof bundle) and the receipt/bundle binding check. scenarios are verifier and release scenarios produced by this SDK: replay each through your own verifier, reference store and release gate under scenario_configuration (testvectors/v2/README.md, cross-sdk), release with the scenario's signed_receipt_b64, and require the same receipt outbox body, allow horizon and release result. Timestamps are relative to the fixed evaluation time 1800000000."

// GenerateCrossSDK returns a fresh Go cross-SDK fixture. Every call uses new
// random keys and hedged ML-DSA-65 signatures. The result is validated with
// VerifyCrossSDK before it is returned.
func GenerateCrossSDK(sdkVersion, generatorNote string) ([]byte, error) {
	var out []byte
	err := catch(func() {
		g := &gen{keys: map[string]*Key{}}
		for _, name := range CrossSDKKeyNames {
			var ed, ml [32]byte
			must(rand.Read(ed[:]))
			must(rand.Read(ml[:]))
			g.addSeededKey(name, ed, ml, true)
		}
		f := g.crossSDKFile()
		f.SDKVersion, f.Generator = sdkVersion, generatorNote
		encoded := must(json.MarshalIndent(f, "", "  "))
		out = append(encoded, '\n')
	})
	if err != nil {
		return nil, err
	}
	if err := VerifyCrossSDK(out); err != nil {
		return nil, fmt.Errorf("generated fixture does not verify: %w", err)
	}
	return out, nil
}

