fn fill_scenarios(k: &Keys) -> Vec<Scenario> {
    let cfg = scenario_config();
    let public: BTreeMap<String, RatifyV2PublicKey> = KEY_NAMES
        .iter()
        .map(|n| (n.to_string(), k.k(n).public))
        .collect();
    let mut out = scenarios(k);
    for sc in &mut out {
        sc.expected = replay_scenario(&cfg, sc, &public, &k.k("verifier").kp, None)
            .unwrap_or_else(|e| panic!("scenario {}: {e}", sc.name));
    }
    out
}

/// README cross-sdk replay procedure through the C ABI: a fresh reference
/// store at `verify_time` and anchored reference journal with every status
/// key configured, `ratify_v2_verify_proof_bundle` with a trust provider
/// returning `trust_root_key` and a status provider returning the scenario
/// evidence, publication at `publish_time`, and `ratify_v2_release_decision`
/// at `release_time` with `release_receipt` (the one just published when
/// `None`).
fn replay_scenario(
    cfg: &ScenarioConfig,
    sc: &Scenario,
    keys: &BTreeMap<String, RatifyV2PublicKey>,
    verifier: &Kp,
    release_receipt: Option<&[u8]>,
) -> Result<ScenarioExpect, String> {
    let key = |name: &str| {
        keys.get(name)
            .copied()
            .ok_or_else(|| format!("key {name:?} is not in the fixture"))
    };
    let mut status_keys = serde_json::Map::new();
    for (issuer, k) in &sc.status_keys {
        let public = key(&k.key)?;
        status_keys.insert(
            issuer.clone(),
            json!({"epoch": k.epoch, "status_key_id": key_id_of(&public).map_err(|e| format!("{e:?}"))?, "public_key": key_json(&public)}),
        );
    }
    let evidence: serde_json::Map<String, Value> = sc
        .status_evidence
        .iter()
        .map(|(issuer, objects)| (issuer.clone(), json!({"mode": "ok", "objects": objects})))
        .collect();
    let inputs = json!({
        "required_scope": sc.required_scope,
        "expected_challenge": sc.expected_challenge,
        "context_policy": sc.context_policy,
        "configured_namespace": cfg.verifier_namespace,
        "configured_replay_epoch": cfg.replay_epoch,
        "configured_verifier_id": verifier.id(),
        "now": sc.verify_time,
        "max_challenge_age_seconds": cfg.max_challenge_age_seconds,
        "future_skew_seconds": cfg.future_skew_seconds,
        "tzdb_version": cfg.tzdb_version,
        "receiver_binding_hook": "absent",
        "trust": {"mode": "ok", "outcome": "trusted", "root_public_key": key_json(&key(&sc.trust_root_key)?)},
        "status_keys": status_keys,
        "status_policy": cfg.status_policy,
        "status_evidence": evidence,
        "journal": {"mode": "anchored"},
        "audience_mode": "ok",
        "rate": "absent",
    });
    if let Some(p) = &sc.context_policy {
        let body = json_bytes(&json!({
            "profile": p.profile,
            "require_bound": p.require_bound,
            "required_fields": p.required_fields,
            "expected_session_context_b64": p.expected_session_context_b64,
        }));
        let digest =
            string(|o| unsafe { ratify_v2_context_policy_digest(body.as_ptr(), body.len(), o) })
                .map_err(|e| format!("context policy: {e:?}"))?;
        if digest != p.digest {
            return Err("context policy digest differs".into());
        }
    }
    let store = RefStore::new(
        sc.verify_time,
        cfg.lease_seconds,
        &cfg.receipt_log_id,
        verifier,
    );
    let mut setup = Setup::build(&inputs, &std::sync::Arc::new(Counts::default()), true);
    setup.claim_cb = Some(store.claim(false));
    let bundle = b64(&json!(sc.bundle_b64));
    let outcome = verify(&setup, &bundle).map_err(|e| format!("verify: {e:?}"))?;
    let c = match (outcome.stage.as_str(), outcome.committed) {
        ("committed", Some(c)) => c,
        (stage, _) => {
            return Err(format!(
                "stage {stage} ({}): {}",
                outcome.class, outcome.message
            ))
        }
    };
    store.set_time(sc.publish_time);
    let published = store
        .publish(&c.claim_id(), &c.body())
        .map_err(|e| format!("publish: {e}"))?;
    store.set_time(sc.release_time);
    let verifier_key = key(&cfg.verifier_key)?;
    let log = cs(&cfg.receipt_log_id);
    let (release_cb, checkpoint) = (store.release(), store.checkpoint());
    let (mut status, mut reason, mut released) = (0i32, ptr::null_mut(), ptr::null_mut());
    check(unsafe {
        ratify_v2_release_decision(
            c.0,
            slice(release_receipt.unwrap_or(&published)),
            &verifier_key,
            log.as_ptr(),
            &release_cb,
            &checkpoint,
            &mut status,
            &mut reason,
            &mut released,
        )
    })
    .map_err(|e| format!("release: {e:?}"))?;
    let reason = take_str(reason);
    let (decision, release_time) = if released.is_null() {
        (None, None)
    } else {
        let decision = string(|o| unsafe {
            ratify_v2_released_string(
                released,
                RatifyV2ReleasedField::RatifyV2ReleasedDecision as i32,
                o,
            )
        })
        .unwrap();
        let (mut rt, mut exp, mut has, mut h) = (0, 0, 0, 0);
        check(unsafe { ratify_v2_released_times(released, &mut rt, &mut exp, &mut has, &mut h) })
            .unwrap();
        unsafe { ratify_v2_released_free(released) };
        (Some(decision), Some(rt))
    };
    Ok(ScenarioExpect {
        receipt_body_b64: enc(&c.body()),
        allow_horizon: c.allow_horizon(),
        signed_receipt_b64: enc(&published),
        release: ScenarioRelease {
            status: unsafe { CStr::from_ptr(ratify_v2_release_status_str(status)) }
                .to_string_lossy()
                .into_owned(),
            reason: (!reason.is_empty()).then_some(reason),
            decision,
            release_time,
        },
    })
}

/// Replay every scenario of a fixture through the C ABI, releasing with the
/// fixture's signed receipt; returns the number replayed (0 when the file
/// carries no scenarios).
fn replay_scenarios(data: &[u8], stem: &str) -> Result<usize, String> {
    let f: FixtureFile = serde_json::from_slice(data).map_err(|e| format!("{stem}: {e}"))?;
    let (cfg, scenarios) = match (&f.scenario_configuration, f.scenarios.is_empty()) {
        (None, true) => return Ok(0),
        (Some(cfg), false) => (cfg, &f.scenarios),
        _ => {
            return Err(format!(
                "{stem}: scenario_configuration and scenarios must appear together"
            ))
        }
    };
    if *cfg != scenario_config() {
        return Err(format!(
            "{stem}: scenario_configuration {cfg:?} differs from the fixed values"
        ));
    }
    let mut public = BTreeMap::new();
    let mut verifier = None;
    for k in &f.keys {
        let kp = Kp::from_seeds(
            &hex::decode(&k.ed25519_seed_hex).unwrap(),
            &hex::decode(&k.ml_dsa_65_seed_hex).unwrap(),
        );
        public.insert(k.name.clone(), kp.public());
        if k.name == cfg.verifier_key {
            verifier = Some(kp);
        }
    }
    let verifier = verifier.ok_or_else(|| format!("{stem}: no verifier key"))?;
    let mut seen = BTreeSet::new();
    for sc in scenarios {
        seen.insert(sc.name.as_str());
        let receipt = b64(&json!(sc.expected.signed_receipt_b64));
        let got = replay_scenario(cfg, sc, &public, &verifier, Some(&receipt))
            .map_err(|e| format!("{stem} scenario {}: {e}", sc.name))?;
        // The producer's receipt is used for release; the one just published
        // carries a different (hedged) signature over the same body.
        let mut want = sc.expected.clone();
        want.signed_receipt_b64 = got.signed_receipt_b64.clone();
        if got != want {
            return Err(format!(
                "{stem} scenario {}: observed {got:?}, want {:?}",
                sc.name, sc.expected
            ));
        }
    }
    if seen != SCENARIO_NAMES.into_iter().collect() {
        return Err(format!("{stem}: scenarios {seen:?}"));
    }
    Ok(scenarios.len())
}

