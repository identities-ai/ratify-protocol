#[test]
fn v2c_external_signer_contract() {
    let witness = Key::fresh("witness");
    let other = Key::fresh("other");
    let entry = witness_entry_json(&witness.id);
    let code6 = 6u32;

    // Direct mode: M (77 bytes) and the 22-byte registry context; no mu.
    let p = Provider::new(
        &witness.ed_seed,
        &witness.ml_seed,
        witness.public,
        Behaviour::Sign,
    );
    let wire = sign_witness_external(&entry, &p.signer(1)).expect("direct-mode signature");
    let signed_signable = signable(6, &wire).unwrap();
    let m_expected = message(code6, &signed_signable).unwrap();
    {
        let reqs = p.requests.lock().unwrap();
        assert_eq!(reqs.len(), 1);
        let (mode, m, ctx, mu_bytes, key, key_id) = &reqs[0];
        assert_eq!(*mode, 1);
        assert_eq!(m, &m_expected);
        assert_eq!(m.len(), 77);
        assert_eq!(ctx.as_slice(), b"ratify-protocol/2/0006");
        assert!(mu_bytes.is_empty(), "direct mode carries no mu");
        assert_eq!(
            (key.ed25519, key.ml_dsa_65.to_vec()),
            (witness.public.ed25519, witness.public.ml_dsa_65.to_vec())
        );
        assert_eq!(key_id, &witness.id);
    }
    check(unsafe {
        ratify_v2_verify_object(
            6,
            wire.as_ptr(),
            wire.len(),
            resolve_context(
                &json!({"witness_key": "w", "head": genesis_head(WITNESS_LOG, None)}),
                &BTreeMap::from([("w".to_string(), witness.public)]),
            )
            .unwrap()
            .as_ptr(),
            ptr::null_mut(),
        )
    })
    .expect("externally signed witness entry verifies");

    // External-mu mode: only the 64-byte mu, equal to ratify_v2_external_mu.
    let mut p = Provider::new(
        &witness.ed_seed,
        &witness.ml_seed,
        witness.public,
        Behaviour::Sign,
    );
    p.mu_context = b"ratify-protocol/2/0006".to_vec();
    sign_witness_external(&entry, &p.signer(2)).expect("external-mu signature");
    {
        let reqs = p.requests.lock().unwrap();
        let (mode, m, ctx, mu_bytes, _, _) = &reqs[0];
        assert_eq!(*mode, 2);
        assert!(ctx.is_empty(), "external-mu mode carries no context");
        assert_eq!(mu_bytes.len(), 64);
        assert_eq!(mu_bytes, &mu(&witness.public, code6, m).unwrap());
    }
    // An external-mu oracle provisioned for another context is caught.
    let mut p = Provider::new(
        &witness.ed_seed,
        &witness.ml_seed,
        witness.public,
        Behaviour::Sign,
    );
    p.mu_context = b"ratify-protocol/2/0001".to_vec();
    assert_eq!(
        class_of(&sign_witness_external(&entry, &p.signer(2))),
        "invalid_signature"
    );

    // Refusals.
    let cases = [
        (
            Behaviour::Refuse,
            1,
            witness.public,
            "configuration_invalid",
        ),
        (Behaviour::Tamper, 1, witness.public, "invalid_signature"),
        (Behaviour::Short, 1, witness.public, "invalid_signature"),
        (Behaviour::Cancel, 1, witness.public, "evaluation_cancelled"),
        (
            Behaviour::PublicKeyCancel,
            1,
            witness.public,
            "evaluation_cancelled",
        ),
        (Behaviour::Sign, 1, other.public, "key_id_mismatch"),
        (Behaviour::Sign, 3, witness.public, "configuration_invalid"),
    ];
    for (behaviour, mode, reported, want) in cases {
        let p = Provider::new(&witness.ed_seed, &witness.ml_seed, reported, behaviour);
        let got = sign_witness_external(&entry, &p.signer(mode));
        assert_eq!(class_of(&got), want, "mode {mode}: {got:?}");
        if mode == 3 {
            assert_eq!(p.calls(), 0, "an unsupported mode invokes no signer method");
        }
    }

    // Exactly one signer per slot.
    let p = Provider::new(
        &witness.ed_seed,
        &witness.ml_seed,
        witness.public,
        Behaviour::Sign,
    );
    let ext = p.signer(1);
    let both: Signed = buf(|o| unsafe {
        ratify_v2_sign_witness_entry(entry.as_ptr(), entry.len(), witness.kp.0, &ext, o)
    });
    assert_eq!(class_of(&both), "bad_argument");
    let neither: Signed = buf(|o| unsafe {
        ratify_v2_sign_witness_entry(entry.as_ptr(), entry.len(), ptr::null(), ptr::null(), o)
    });
    assert_eq!(class_of(&neither), "null_pointer");

    // An issuer-duty refusal runs no signer method (SPEC-v2 §3.2).
    let issuer = Key::fresh("issuer");
    let cert = json_bytes(&json!({
        "version": 2,
        "cert_id": "cert-duty",
        "issuer_id": issuer.id,
        "issuer_pub_key": issuer.json(),
        "subject_id": witness.id,
        "subject_pub_key": witness.json(),
        "scope": ["data:read"],
        "constraints": [],
        "issued_at": NOW,
        "expires_at": NOW,
    }));
    let p = Provider::new(
        &issuer.ed_seed,
        &issuer.ml_seed,
        issuer.public,
        Behaviour::Sign,
    );
    let ext = p.signer(1);
    let refused: Signed = buf(|o| unsafe {
        ratify_v2_sign_delegation_certificate(cert.as_ptr(), cert.len(), ptr::null(), &ext, o)
    });
    assert_eq!(class_of(&refused), "malformed");
    assert_eq!(p.calls(), 0, "a refused certificate invoked the signer");
}
