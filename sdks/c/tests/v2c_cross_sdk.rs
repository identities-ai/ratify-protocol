/// The ABI verify context of a fixture object, with this fixture's key
/// names resolved.
fn resolve_context(
    vc: &Value,
    keys: &BTreeMap<String, RatifyV2PublicKey>,
) -> Option<std::ffi::CString> {
    let obj = vc.as_object()?;
    if obj.is_empty() {
        return None;
    }
    let mut v = vc.clone();
    for f in ["status_key", "witness_key", "verifier_key"] {
        if let Some(name) = v.get(f).and_then(Value::as_str).map(str::to_owned) {
            v[f] = key_json(&keys[&name]);
        }
    }
    if let Some(name) = v
        .get("rotation_state")
        .and_then(|r| r.get("current_key"))
        .and_then(Value::as_str)
        .map(str::to_owned)
    {
        v["rotation_state"]["current_key"] = key_json(&keys[&name]);
    }
    Some(cs(&v.to_string()))
}

/// The granular C-ABI check of one fixture; returns the number of
/// signatures checked.
fn granular(data: &[u8], stem: &str) -> Result<usize, String> {
    let f: Value = serde_json::from_slice(data).map_err(|e| e.to_string())?;
    if s(&f["sdk"]) != stem || i(&f["version"]) != 2 {
        return Err(format!("sdk {} / version {}", f["sdk"], f["version"]));
    }
    let mut keys = BTreeMap::new();
    let mut ids = BTreeMap::new();
    for k in arr(&f["keys"]) {
        let name = s(&k["name"]);
        let kp = Kp::from_seeds(
            &hex::decode(s(&k["ed25519_seed_hex"])).unwrap(),
            &hex::decode(s(&k["ml_dsa_65_seed_hex"])).unwrap(),
        );
        let public = kp.public();
        if key_json(&public) != k["public_key"] {
            return Err(format!("key {name}: seeds do not derive the public key"));
        }
        if kp.id() != s(&k["key_id_v2"]) || key_id_of(&public).unwrap() != s(&k["key_id_v2"]) {
            return Err(format!("key {name}: key_id_v2 differs"));
        }
        if v1_id(&public) != s(&k["v1_key_id_128"]) {
            return Err(format!("key {name}: v1 key ID differs"));
        }
        keys.insert(name.clone(), public);
        ids.insert(name, s(&k["key_id_v2"]));
    }
    for n in KEY_NAMES {
        if !keys.contains_key(n) {
            return Err(format!("missing key {n}"));
        }
    }
    let (mut kinds, mut codes, mut checked) = (BTreeSet::new(), BTreeSet::new(), 0usize);
    for o in arr(&f["objects"]) {
        let name = s(&o["name"]);
        let kind = s(&o["kind"]);
        kinds.insert(kind.clone());
        let wire = b64(&o["wire_b64"]);
        let fail = |m: String| format!("{stem}/{name}: {m}");
        if kind == "receipt_bundle_binding" {
            let bundle = b64(&o["bundle_b64"]);
            if canonicalize(8, &wire).as_deref() != Ok(wire.as_slice())
                || canonicalize(2, &bundle).as_deref() != Ok(bundle.as_slice())
            {
                return Err(fail("re-encoding is not byte-identical".into()));
            }
            check(unsafe {
                ratify_v2_receipt_bundle_binding_check(
                    wire.as_ptr(),
                    wire.len(),
                    bundle.as_ptr(),
                    bundle.len(),
                    ptr::null_mut(),
                )
            })
            .map_err(|e| fail(format!("binding: {e:?}")))?;
            continue;
        }
        let code = kind_code(&kind);
        match canonicalize(code, &wire) {
            Ok(re) if re == wire => {}
            other => {
                return Err(fail(format!(
                    "re-encoding is not byte-identical: {:?}",
                    other.err()
                )))
            }
        }
        let ctx = resolve_context(&o["verify"], &keys);
        check(unsafe {
            ratify_v2_verify_object(
                code,
                wire.as_ptr(),
                wire.len(),
                ctx.as_ref().map_or(ptr::null(), |c| c.as_ptr()),
                ptr::null_mut(),
            )
        })
        .map_err(|e| fail(format!("verify: {e:?}")))?;
        let wire_text = String::from_utf8_lossy(&wire).into_owned();
        for sig in arr(&o["signatures"]) {
            let field = s(&sig["field"]);
            let code = u(&sig["object_type_code"]) as u32;
            codes.insert(code);
            let signer = s(&sig["signer"]);
            let key = keys
                .get(&signer)
                .ok_or_else(|| fail(format!("{field}: unknown signer {signer}")))?;
            let sp = projection(&wire, &field, code)
                .map_err(|e| fail(format!("{field}: projection {e:?}")))?;
            let m = message(code, &sp).unwrap();
            let ctx = context(code).unwrap();
            let ok = enc(&sp) == s(&sig["signable_b64"])
                && hex::encode(sha384(&sp)) == s(&sig["signable_sha384_hex"])
                && enc(&m) == s(&sig["message_b64"])
                && m.len() == 77
                && ctx == s(&sig["mldsa_context"]).as_bytes()
                && ctx.len() == 22
                && enc(&shake256_64(&key.ml_dsa_65)) == s(&sig["mldsa_tr_b64"])
                && enc(&mu(key, code, &m).unwrap()) == s(&sig["mldsa_mu_b64"])
                && ids[&signer] == s(&sig["signer_key_id_v2"]);
            if !ok {
                return Err(fail(format!("{field}: projection or transcript differs")));
            }
            let (ed, ml) = (
                s(&sig["signature"]["ed25519"]),
                s(&sig["signature"]["ml_dsa_65"]),
            );
            if !wire_text.contains(&format!("\"{ed}\""))
                || !wire_text.contains(&format!("\"{ml}\""))
            {
                return Err(fail(format!(
                    "{field}: pinned signature is not carried by the wire object"
                )));
            }
            verify_statement(code, &sp, &b64(&json!(ed)), &b64(&json!(ml)), key)
                .map_err(|e| fail(format!("{field}: {e:?}")))?;
            checked += 1;
        }
    }
    for kind in [
        "delegation_certificate",
        "proof_bundle",
        "revocation_list",
        "revocation_push",
        "key_rotation_statement",
        "witness_entry",
        "transaction_receipt",
        "verification_receipt",
        "receipt_bundle_binding",
    ] {
        if !kinds.contains(kind) {
            return Err(format!("{stem}: no {kind} object"));
        }
    }
    if codes != (1..=9).collect() {
        return Err(format!("{stem}: signature codes {codes:?}"));
    }
    Ok(checked)
}

/// Verify a fixture; returns (signatures checked, scenarios replayed).
fn verify_fixture(data: &[u8], stem: &str) -> Result<(usize, usize), String> {
    let sdk = cs(stem);
    check(unsafe { ratify_v2_cross_sdk_fixture_verify(data.as_ptr(), data.len(), sdk.as_ptr()) })
        .map_err(|e| format!("{stem}: ratify_v2_cross_sdk_fixture_verify: {e:?}"))?;
    let signatures = granular(data, stem)?;
    let scenarios = replay_scenarios(data, stem)?;
    if scenarios == 0 {
        return Err(format!(
            "{stem}.json has no verifier and release scenarios (SPEC-v2 §8.1)"
        ));
    }
    Ok((signatures, scenarios))
}

