type Signed = R<Vec<u8>>;

fn sign_cert(
    issuer: &Key,
    subject: &Key,
    cert_id: &str,
    scope: &[&str],
    constraints: Value,
) -> Vec<u8> {
    let c = json!({
        "version": 2,
        "cert_id": cert_id,
        "issuer_id": issuer.id,
        "issuer_pub_key": issuer.json(),
        "subject_id": subject.id,
        "subject_pub_key": subject.json(),
        "scope": scope,
        "constraints": constraints,
        "issued_at": NOW - 3600,
        "expires_at": NOW + 86400,
    });
    let data = json_bytes(&c);
    let r: Signed = buf(|o| unsafe {
        ratify_v2_sign_delegation_certificate(
            data.as_ptr(),
            data.len(),
            issuer.kp.0,
            ptr::null(),
            o,
        )
    });
    r.expect("sign certificate")
}

fn sign_bundle(
    agent: &Key,
    verifier_id: &str,
    certs: &[&[u8]],
    challenge: &[u8],
    session: Option<&[u8]>,
    stream: Option<(&[u8], i64)>,
) -> Vec<u8> {
    let b = json!({
        "version": 2,
        "verifier_id": verifier_id,
        "agent_id": agent.id,
        "agent_pub_key": agent.json(),
        "delegations": certs.iter().map(|c| parse(c)).collect::<Vec<_>>(),
        "challenge": enc(challenge),
        "challenge_at": NOW - 10,
        "session_context": session.map(enc),
        "stream_id": stream.map(|(id, _)| enc(id)),
        "stream_seq": stream.map(|(_, seq)| seq),
    });
    let data = json_bytes(&b);
    let r: Signed = buf(|o| unsafe {
        ratify_v2_sign_proof_bundle(data.as_ptr(), data.len(), agent.kp.0, ptr::null(), o)
    });
    r.expect("sign proof bundle")
}

/// The signature value pinned in the wire for `field`.
fn wire_signature(wire: &[u8], field: &str) -> Value {
    let v = parse(wire);
    if let Some(rest) = field.strip_prefix("delegations[") {
        let i: usize = rest.trim_end_matches("].signature").parse().unwrap();
        return v["delegations"][i]["signature"].clone();
    }
    if let Some(party) = field
        .strip_prefix("party_signatures[")
        .and_then(|r| r.strip_suffix(']'))
    {
        return arr(&v["party_signatures"])
            .into_iter()
            .find(|s| s["party_id"] == party)
            .map(|s| s["signature"].clone())
            .unwrap_or(Value::Null);
    }
    v[field].clone()
}

/// The signable projection of `field` through the ABI.
fn projection(wire: &[u8], field: &str, code: u32) -> R<Vec<u8>> {
    if let Some(rest) = field.strip_prefix("delegations[") {
        let i: usize = rest.trim_end_matches("].signature").parse().unwrap();
        let cert = canon(&parse(wire)["delegations"][i]);
        return signable(1, &cert);
    }
    signable(code, wire)
}

fn sig_entry(field: &str, code: u32, signer: &Key, wire: &[u8]) -> SignatureEntry {
    let projected = projection(wire, field, code).expect("projection");
    let m = message(code, &projected).unwrap();
    let ctx = context(code).unwrap();
    let sig = wire_signature(wire, field);
    SignatureEntry {
        field: field.into(),
        object_type_code: i64::from(code),
        signer: signer.name.into(),
        signer_key_id_v2: signer.id.clone(),
        signable_b64: enc(&projected),
        signable_sha384_hex: hex::encode(sha384(&projected)),
        message_b64: enc(&m),
        mldsa_context: String::from_utf8(ctx).unwrap(),
        mldsa_tr_b64: enc(&shake256_64(&signer.public.ml_dsa_65)),
        mldsa_mu_b64: enc(&mu(&signer.public, code, &m).unwrap()),
        signature: BTreeMap::from([
            ("ed25519".to_string(), s(&sig["ed25519"])),
            ("ml_dsa_65".to_string(), s(&sig["ml_dsa_65"])),
        ]),
    }
}

