#[derive(Clone, Copy, PartialEq, Eq)]
enum Behaviour {
    Sign,
    Refuse,
    Tamper,
    Short,
    Cancel,
    PublicKeyCancel,
}

/// One request as the provider saw it: mode, M, context, mu, key, key ID.
type SeenRequest = (i32, Vec<u8>, Vec<u8>, Vec<u8>, RatifyV2PublicKey, String);

/// A provider holding its own copy of the key (an HSM stand-in). In
/// external-μ mode it emulates the μ oracle like the Rust and Go tests:
/// fips204 has no external-μ entry point, so it signs `M` under the
/// registry context it was provisioned for, and the SDK verifies the result.
struct Provider {
    ed: SigningKey,
    ml: ml_dsa_65::PrivateKey,
    reported_key: RatifyV2PublicKey,
    behaviour: Behaviour,
    mu_context: Vec<u8>,
    calls: Mutex<usize>,
    requests: Mutex<Vec<SeenRequest>>,
}

struct SeedOnce([u8; 32], bool);

impl rand_core::RngCore for SeedOnce {
    fn next_u32(&mut self) -> u32 {
        rand_core::impls::next_u32_via_fill(self)
    }
    fn next_u64(&mut self) -> u64 {
        rand_core::impls::next_u64_via_fill(self)
    }
    fn fill_bytes(&mut self, dest: &mut [u8]) {
        self.try_fill_bytes(dest).expect("seed used once")
    }
    fn try_fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), rand_core::Error> {
        assert!(
            !self.1 && dest.len() == 32,
            "ML-DSA keygen draws exactly one 32-byte seed"
        );
        dest.copy_from_slice(&self.0);
        self.1 = true;
        Ok(())
    }
}

impl rand_core::CryptoRng for SeedOnce {}

impl Provider {
    fn new(
        ed_seed: &[u8; 32],
        ml_seed: &[u8; 32],
        reported_key: RatifyV2PublicKey,
        behaviour: Behaviour,
    ) -> Provider {
        let (_, ml) =
            ml_dsa_65::try_keygen_with_rng(&mut SeedOnce(*ml_seed, false)).expect("keygen");
        Provider {
            ed: SigningKey::from_bytes(ed_seed),
            ml,
            reported_key,
            behaviour,
            mu_context: Vec::new(),
            calls: Mutex::new(0),
            requests: Mutex::new(Vec::new()),
        }
    }

    fn signer(&self, mode: i32) -> RatifyV2ExternalSigner {
        RatifyV2ExternalSigner {
            user: self as *const Provider as *mut c_void,
            mode,
            public_key: Some(provider_public_key),
            sign: Some(provider_sign),
        }
    }

    fn calls(&self) -> usize {
        *self.calls.lock().unwrap()
    }
}

unsafe extern "C" fn provider_public_key(user: *mut c_void, out: *mut RatifyV2PublicKey) -> i32 {
    let p = &*(user as *const Provider);
    *p.calls.lock().unwrap() += 1;
    if p.behaviour == Behaviour::PublicKeyCancel {
        return RatifyV2Code::RatifyV2ErrCancelled as i32;
    }
    *out = p.reported_key;
    0
}

unsafe extern "C" fn provider_sign(
    user: *mut c_void,
    req: *const RatifyV2SignRequest,
    out: *mut RatifyV2Signature,
) -> i32 {
    let p = &*(user as *const Provider);
    *p.calls.lock().unwrap() += 1;
    let r = &*req;
    let (m, ctx, mu) = (
        slice_in(r.message),
        slice_in(r.ml_dsa_context),
        slice_in(r.ml_dsa_mu),
    );
    p.requests.lock().unwrap().push((
        r.mode,
        m.clone(),
        ctx.clone(),
        mu.clone(),
        *r.public_key,
        cstr_in(r.key_id),
    ));
    match p.behaviour {
        Behaviour::Refuse => return RatifyV2Code::RatifyV2StoreUnavailable as i32,
        Behaviour::Cancel => return RatifyV2Code::RatifyV2ErrCancelled as i32,
        _ => {}
    }
    let context = if r.mode == RatifyV2SignerMode::RatifyV2SignerDirect as i32 {
        ctx
    } else {
        p.mu_context.clone()
    };
    let ed = p.ed.sign(&m).to_bytes();
    let ml = p.ml.try_sign(&m, &context).expect("ML-DSA sign");
    let o = &mut *out;
    o.ed25519.copy_from_slice(&ed);
    o.ed25519_len = 64;
    o.ml_dsa_65.copy_from_slice(&ml);
    o.ml_dsa_65_len = 3309;
    match p.behaviour {
        Behaviour::Tamper => o.ml_dsa_65[0] ^= 1,
        Behaviour::Short => o.ml_dsa_65_len = 100,
        _ => {}
    }
    0
}

