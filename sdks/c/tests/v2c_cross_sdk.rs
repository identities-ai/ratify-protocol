fn objects(k: &Keys) -> Vec<ObjectEntry> {
    let mut out = Vec::new();
    let (root, inter, agent, verifier) = (
        k.k("root"),
        k.k("intermediate"),
        k.k("agent"),
        k.k("verifier"),
    );
    let cert_obj = |name: &str, desc: &str, wire: &[u8], issuer: &Key, subject: &Key| {
        let mut o = object(name, "delegation_certificate", desc, wire);
        o.signatures = vec![sig_entry("signature", 1, issuer, wire)];
        o.digests = BTreeMap::from([
            ("issuer_key_id_v2".to_string(), issuer.id.clone()),
            ("subject_key_id_v2".to_string(), subject.id.clone()),
        ]);
        o
    };

    let root_cert = sign_cert(
        root,
        inter,
        "cert-root",
        &["data:read", "files:read", "identity:delegate"],
        json!([]),
    );
    out.push(cert_obj(
        "delegation_root_to_intermediate",
        "Root delegates to an intermediate, including identity:delegate.",
        &root_cert,
        root,
        inter,
    ));
    let leaf_cons = sign_cert(
        inter,
        agent,
        "cert-leaf-constrained",
        &["data:read"],
        every_constraint(),
    );
    out.push(cert_obj(
        "delegation_every_registered_constraint_and_extension",
        "Every type in the closed v2 constraint registry (max_rate, ratify.receiver_audience, resource_path, time_window, max_amount) plus the extension evaluator type com.ratifyprotocol.max_count.",
        &leaf_cons,
        inter,
        agent,
    ));

    let op = json_bytes(&json!({
        "required_scope": "data:read",
        "operation": "records.get",
        "resource_id": "customer/123",
        "requested_path": "/v1/customers/123",
    }));
    let request =
        buf(|o| unsafe { ratify_v2_operation_context_hash(op.as_ptr(), op.len(), o) }).unwrap();
    let session = session_context(
        &verifier.id,
        &agent.id,
        "session-01",
        "invocation-01",
        &request,
    );
    let bundle_sigs = |wire: &[u8], issuers: &[&Key]| -> Vec<SignatureEntry> {
        let mut v = vec![sig_entry("challenge_sig", 2, agent, wire)];
        for (i, issuer) in issuers.iter().enumerate() {
            v.push(sig_entry(
                &format!("delegations[{i}].signature"),
                1,
                issuer,
                wire,
            ));
        }
        v
    };
    let bundle_digests = |wire: &[u8], with_session: bool| -> BTreeMap<String, String> {
        let mut d = BTreeMap::from([
            (
                "delegation_digest_hex".to_string(),
                digest_hex(|o| unsafe {
                    ratify_v2_delegation_digest(wire.as_ptr(), wire.len(), o)
                }),
            ),
            ("bundle_hash_v2".to_string(), bundle_hash(wire)),
        ]);
        if with_session {
            d.insert("session_context_hex".into(), hex::encode(&session));
        }
        d
    };
    let challenge_a: Vec<u8> = (0..32u8).map(|i| 0xa0 + i).collect();
    let challenge_b: Vec<u8> = (0..32u8).map(|i| 0xb0 + i).collect();

    let plain_leaf = sign_cert(
        inter,
        agent,
        "cert-leaf",
        &["data:read", "files:read"],
        json!([]),
    );
    let plain_wire = sign_bundle(
        agent,
        &verifier.id,
        &[&plain_leaf, &root_cert],
        &challenge_a,
        Some(&session),
        None,
    );
    let mut o = object(
        "proof_bundle_two_link_bound_context",
        "proof_bundle",
        "Leaf-to-root chain with a bound session_context and null stream fields.",
        &plain_wire,
    );
    o.signatures = bundle_sigs(&plain_wire, &[inter, root]);
    o.digests = bundle_digests(&plain_wire, true);
    o.digests.insert(
        "challenge_claim_digest_hex".into(),
        digest_hex(|b| unsafe {
            ratify_v2_challenge_claim_digest(challenge_a.as_ptr(), challenge_a.len(), b)
        }),
    );
    let ns = NAMESPACE.as_bytes();
    o.digests.insert(
        "claim_id".into(),
        string(|s| unsafe {
            ratify_v2_claim_id(
                ns.as_ptr(),
                ns.len(),
                REPLAY_EPOCH,
                challenge_a.as_ptr(),
                challenge_a.len(),
                s,
            )
        })
        .unwrap(),
    );
    o.digests
        .insert("claim_verifier_namespace".into(), NAMESPACE.into());
    o.digests
        .insert("claim_replay_epoch".into(), REPLAY_EPOCH.to_string());
    out.push(o);

    let ext_wire = sign_bundle(
        agent,
        &verifier.id,
        &[&leaf_cons, &root_cert],
        &challenge_b,
        Some(&session),
        None,
    );
    let mut o = object(
        "proof_bundle_constrained_chain",
        "proof_bundle",
        "Chain whose leaf is the constrained certificate above, with a bound session_context.",
        &ext_wire,
    );
    o.signatures = bundle_sigs(&ext_wire, &[inter, root]);
    o.digests = bundle_digests(&ext_wire, true);
    out.push(o);

    let stream_wire = sign_bundle(
        agent,
        &verifier.id,
        &[],
        &challenge_a,
        None,
        Some((&[0x5a; 32], 1)),
    );
    let mut o = object(
        "proof_bundle_empty_chain_stream_bound",
        "proof_bundle",
        "Empty delegations array, null session_context, and a bound stream at sequence 1.",
        &stream_wire,
    );
    o.signatures = bundle_sigs(&stream_wire, &[]);
    o.digests = bundle_digests(&stream_wire, false);
    out.push(o);

    // Status objects.
    let status_obj =
        |name: &str, kind: &str, desc: &str, wire: &[u8], issuer: &Key, status: &Key, code: u32| {
            let mut o = object(name, kind, desc, wire);
            o.verify = json!({"bound_issuer_id": issuer.id, "status_key": status.name});
            o.signatures = vec![sig_entry("signature", code, status, wire)];
            let digest = digest_hex(|b| unsafe {
                ratify_v2_status_evidence_digest(code as i32, wire.as_ptr(), wire.len(), b)
            });
            o.digests = BTreeMap::from([(
                "status_evidence_digest".to_string(),
                format!("sha384:{digest}"),
            )]);
            (o, digest)
        };
    let sign_list = |status: &Key, issuer: &Key, sequence: i64, revoked: &[&str]| -> Vec<u8> {
        let l = json_bytes(&json!({
            "version": 2,
            "issuer_id": issuer.id,
            "updated_at": NOW - 60,
            "next_update": NOW + 3600,
            "sequence": sequence,
            "revoked": revoked.iter().map(|c| json!({"cert_id": c})).collect::<Vec<_>>(),
        }));
        let id = cs(&issuer.id);
        let r: Signed = buf(|o| unsafe {
            ratify_v2_sign_revocation_list(
                l.as_ptr(),
                l.len(),
                id.as_ptr(),
                &status.public,
                status.kp.0,
                ptr::null(),
                o,
            )
        });
        r.expect("sign list")
    };
    let (status_root, status_inter) = (k.k("status_root"), k.k("status_intermediate"));
    let root_list = sign_list(status_root, root, 7, &["cert-a", "cert-b"]);
    let (o, root_list_digest) = status_obj(
        "revocation_list_root",
        "revocation_list",
        "Snapshot signed under code 0x0003 by the status key bound to the root issuer.",
        &root_list,
        root,
        status_root,
        3,
    );
    out.push(o);
    let inter_list = sign_list(status_inter, inter, 1, &[]);
    let (o, inter_list_digest) = status_obj(
        "revocation_list_intermediate_empty",
        "revocation_list",
        "Empty snapshot signed by the status key bound to the intermediate issuer.",
        &inter_list,
        inter,
        status_inter,
        3,
    );
    out.push(o);
    let push = json_bytes(&json!({
        "version": 2,
        "issuer_id": root.id,
        "sequence": 8,
        "pushed_at": NOW - 30,
        "revoked": [{"cert_id": "cert-c"}],
    }));
    let root_id = cs(&root.id);
    let push_wire = buf(|o| unsafe {
        ratify_v2_sign_revocation_push(
            push.as_ptr(),
            push.len(),
            root_id.as_ptr(),
            &status_root.public,
            status_root.kp.0,
            ptr::null(),
            o,
        )
    })
    .expect("sign push");
    out.push(
        status_obj(
            "revocation_push",
            "revocation_push",
            "Push signed under code 0x0005 by the bound status key.",
            &push_wire,
            root,
            status_root,
            5,
        )
        .0,
    );

    // Key rotation.
    let (old, new) = (k.k("rotation_genesis"), k.k("rotation_second"));
    let stmt = json_bytes(&json!({
        "version": 2,
        "authority_id": ROTATION_AUTHORITY,
        "recovery_epoch": 1,
        "role": "issuer",
        "sequence": 1,
        "previous_statement_hash": enc(&[0u8; 48]),
        "old_key": old.json(),
        "new_key": new.json(),
        "old_key_id": old.id,
        "new_key_id": new.id,
        "issued_at": NOW - 600,
        "not_before": NOW - 600,
    }));
    let wire = buf(|o| unsafe {
        ratify_v2_sign_key_rotation_statement(
            stmt.as_ptr(),
            stmt.len(),
            old.kp.0,
            ptr::null(),
            new.kp.0,
            ptr::null(),
            o,
        )
    })
    .expect("sign rotation");
    let mut o = object(
        "key_rotation_genesis",
        "key_rotation_statement",
        "Genesis rotation: the old key signs code 0x0004 and the new key signs the identical body under code 0x0009.",
        &wire,
    );
    o.verify = json!({
        "rotation_state": {
            "authority_id": ROTATION_AUTHORITY,
            "recovery_epoch": 1,
            "role": "issuer",
            "sequence": 0,
            "head_hash_b64": enc(&[0u8; 48]),
            "current_key": old.name,
            "used_key_ids": [old.id],
        },
        "now": NOW,
        "future_skew_seconds": 5,
    });
    o.signatures = vec![
        sig_entry("old_signature", 4, old, &wire),
        sig_entry("new_signature", 9, new, &wire),
    ];
    o.digests = BTreeMap::from([(
        "statement_body_digest_hex".to_string(),
        digest_hex(|b| unsafe { ratify_v2_object_body_digest(4, wire.as_ptr(), wire.len(), b) }),
    )]);
    out.push(o);

    // Witness entry, signed through an external signer C callback.
    let witness = k.k("witness");
    let provider = Provider::new(
        &witness.ed_seed,
        &witness.ml_seed,
        witness.public,
        Behaviour::Sign,
    );
    let ext = provider.signer(RatifyV2SignerMode::RatifyV2SignerDirect as i32);
    let wire = sign_witness_external(&witness_entry_json(&witness.id), &ext)
        .expect("external witness signature");
    let mut o = object(
        "witness_entry_genesis",
        "witness_entry",
        "Genesis witness entry; prev_hash is 48 zero bytes.",
        &wire,
    );
    o.verify = json!({"witness_key": witness.name, "head": genesis_head(WITNESS_LOG, None)});
    o.signatures = vec![sig_entry("signature", 6, witness, &wire)];
    o.digests = BTreeMap::from([(
        "statement_body_digest_hex".to_string(),
        digest_hex(|b| unsafe { ratify_v2_object_body_digest(6, wire.as_ptr(), wire.len(), b) }),
    )]);
    out.push(o);

    out.push(transaction_object(k));

    // Verification receipts, each paired with its bundle.
    let mut evidence = vec![
        json!({"issuer_id": root.id, "status_key_id": status_root.id, "sequence": 7, "object_type_code": 3, "digest": format!("sha384:{root_list_digest}")}),
        json!({"issuer_id": inter.id, "status_key_id": status_inter.id, "sequence": 1, "object_type_code": 3, "digest": format!("sha384:{inter_list_digest}")}),
    ];
    evidence.sort_by(|a, b| {
        (s(&a["issuer_id"]), s(&a["status_key_id"]))
            .cmp(&(s(&b["issuer_id"]), s(&b["status_key_id"])))
    });
    let mut issuer_ids = vec![root.id.clone(), inter.id.clone()];
    issuer_ids.sort();
    // The expected session context is excluded from the policy digest.
    let policy = json_bytes(&json!({
        "profile": VERIFY_POLICY,
        "require_bound": true,
        "required_fields": VERIFY_POLICY_FIELDS,
        "expected_session_context_b64": enc(&session),
    }));
    let policy_digest =
        string(|o| unsafe { ratify_v2_context_policy_digest(policy.as_ptr(), policy.len(), o) })
            .unwrap();
    let receipt =
        |log_id: &str, bundle_wire: &[u8], granted: &[&str], evaluators: Option<Value>| -> Value {
            let mut r = json!({
                "version": 2,
                "log_id": log_id,
                "sequence": 1,
                "previous_receipt_hash": enc(&[0u8; 48]),
                "verifier_id": verifier.id,
                "agent_id": agent.id,
                "bundle_hash": bundle_hash(bundle_wire),
                "issuer_ids": issuer_ids,
                "decision": "allow",
                "decision_reason": "authorized",
                "identity_status": "authorized_agent",
                "trust_assessment": "trusted",
                "status_assessment": "current",
                "challenge_assessment": "current",
                "context_assessment": "bound",
                "context_policy_digest": policy_digest,
                "verified_at": NOW,
                "required_scope": "data:read",
                "granted_scope": granted,
                "status_evidence_digests": evidence,
            });
            if let Some(e) = evaluators {
                r["constraint_evaluators"] = e;
            }
            r
        };
    let mut add_receipt = |name: &str,
                           desc: &str,
                           log_id: &str,
                           body: Value,
                           bundle_wire: &[u8]| {
        let data = json_bytes(&body);
        let wire = buf(|o| unsafe {
            ratify_v2_sign_verification_receipt(
                data.as_ptr(),
                data.len(),
                verifier.kp.0,
                ptr::null(),
                o,
            )
        })
        .expect("sign receipt");
        let mut o = object(name, "verification_receipt", desc, &wire);
        o.verify = json!({"verifier_key": verifier.name, "head": genesis_head(log_id, Some(&verifier.id))});
        o.signatures = vec![sig_entry("signature", 8, verifier, &wire)];
        let outbox =
            buf(|b| unsafe { ratify_v2_verification_receipt_body(wire.as_ptr(), wire.len(), b) })
                .unwrap();
        o.digests = BTreeMap::from([
            (
                "statement_body_digest_hex".to_string(),
                digest_hex(|b| unsafe {
                    ratify_v2_object_body_digest(8, wire.as_ptr(), wire.len(), b)
                }),
            ),
            ("receipt_outbox_body_b64".to_string(), enc(&outbox)),
        ]);
        out.push(o);
        let mut binding = object(
            &format!("{name}/bundle_binding"),
            "receipt_bundle_binding",
            "The receipt above (wire_b64) with the proof bundle it was issued for (bundle_b64): bundle_hash, verifier_id, agent_id, and issuer_ids bind.",
            &wire,
        );
        binding.bundle_b64 = Some(enc(bundle_wire));
        out.push(binding);
    };
    add_receipt(
        "verification_receipt_allow_genesis",
        "Genesis allow receipt for proof_bundle_two_link_bound_context, signed under code 0x0008 by the caller-authenticated verifier key.",
        RECEIPT_LOG_A,
        receipt(RECEIPT_LOG_A, &plain_wire, &["data:read", "files:read"], None),
        &plain_wire,
    );
    let profile = cs("com.ratifyprotocol.max_count/v1");
    let kind = cs("com.ratifyprotocol.max_count");
    let profile_digest = string(|o| unsafe {
        ratify_v2_constraint_profile_digest(profile.as_ptr(), kind.as_ptr(), o)
    })
    .unwrap();
    add_receipt(
        "verification_receipt_constraint_evaluators",
        "Genesis allow receipt for proof_bundle_constrained_chain carrying the signed constraint_evaluators member for com.ratifyprotocol.max_count/v1.",
        RECEIPT_LOG_B,
        receipt(
            RECEIPT_LOG_B,
            &ext_wire,
            &["data:read"],
            Some(json!([{"type": "com.ratifyprotocol.max_count", "profile_digest": profile_digest}])),
        ),
        &ext_wire,
    );
    out
}

fn transaction_object(k: &Keys) -> ObjectEntry {
    let verifier = k.k("verifier");
    let (uri, tx_id) = ("https://example.com/terms/purchase/v1", "tx-0001");
    let (uri_c, tx_c) = (cs(uri), cs(tx_id));
    let terms = TX_TERMS.as_bytes();
    let tx_context = buf(|o| unsafe {
        ratify_v2_transaction_context_hash(
            tx_c.as_ptr(),
            uri_c.as_ptr(),
            terms.as_ptr(),
            terms.len(),
            o,
        )
    })
    .expect("transaction context");
    let mut digests = BTreeMap::from([(
        "transaction_context_hex".to_string(),
        hex::encode(&tx_context),
    )]);
    let parties = [
        (
            "party-a",
            "buyer",
            "transact:purchase",
            k.k("agent"),
            k.k("root"),
        ),
        (
            "party-b",
            "seller",
            "transact:sell",
            k.k("party_b_agent"),
            k.k("party_b_root"),
        ),
    ];
    let mut party_json = Vec::new();
    for (id, role, scope, agent, root) in parties {
        let sc = cs(scope);
        let req = buf(|o| unsafe {
            ratify_v2_transaction_party_request_hash(
                tx_context.as_ptr(),
                tx_context.len(),
                sc.as_ptr(),
                o,
            )
        })
        .expect("party request hash");
        let (session, invocation) = (format!("session-{id}"), format!("invocation-{id}"));
        let ctx = session_context(&verifier.id, &agent.id, &session, &invocation, &req);
        let c = sign_cert(root, agent, &format!("cert-{id}"), &[scope], json!([]));
        let challenge: Vec<u8> = (0..32u8).map(|i| 0xa0 + i).collect();
        let b = sign_bundle(agent, &verifier.id, &[&c], &challenge, Some(&ctx), None);
        let hash = bundle_hash(&b);
        digests.insert(
            format!("{id}.transaction_party_request_hash_hex"),
            hex::encode(&req),
        );
        digests.insert(format!("{id}.session_context_hex"), hex::encode(&ctx));
        digests.insert(format!("{id}.proof_bundle_hash"), hash.clone());
        party_json.push(json!({
            "party_id": id,
            "role": role,
            "agent_id": agent.id,
            "agent_pub_key": agent.json(),
            "verifier_id": verifier.id,
            "workspace_id": WORKSPACE,
            "session_id": session,
            "invocation_id": invocation,
            "required_scope": scope,
            "proof_bundle_hash": hash,
            "proof_bundle": parse(&b),
        }));
    }
    let mut receipt = json_bytes(&json!({
        "version": 2,
        "transaction_id": tx_id,
        "created_at": NOW - 5,
        "terms_schema_uri": uri,
        "terms_canonical_json": enc(terms),
        "parties": party_json,
        "party_signatures": [],
    }));
    for (id, _, _, agent, _) in parties {
        let p = cs(id);
        receipt = buf(|o| unsafe {
            ratify_v2_sign_transaction_receipt_party(
                receipt.as_ptr(),
                receipt.len(),
                p.as_ptr(),
                agent.kp.0,
                ptr::null(),
                o,
            )
        })
        .expect("party signature");
    }
    let wire = canonicalize(7, &receipt).expect("signed transaction receipt decodes");
    assert_eq!(
        wire, receipt,
        "the signed transaction receipt is already canonical"
    );
    let mut o = object(
        "transaction_receipt_two_parties",
        "transaction_receipt",
        "Two parties sign the identical signable object under code 0x0007.",
        &wire,
    );
    for (id, _, _, agent, _) in parties {
        o.signatures.push(sig_entry(
            &format!("party_signatures[{id}]"),
            7,
            agent,
            &wire,
        ));
    }
    o.digests = digests;
    o
}

