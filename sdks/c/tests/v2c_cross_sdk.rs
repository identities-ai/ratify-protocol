// Harness helpers

fn sha384(b: &[u8]) -> Vec<u8> {
    Sha384::digest(b).to_vec()
}

fn shake256_64(b: &[u8]) -> Vec<u8> {
    let mut h = sha3::Shake256::default();
    h.update(b);
    let mut out = vec![0u8; 64];
    h.finalize_xof().read(&mut out);
    out
}

fn v1_id(k: &RatifyV2PublicKey) -> String {
    let text = cs(&key_json(k).to_string());
    let mut err = ptr::null_mut();
    let p = unsafe { ratify_derive_id(text.as_ptr(), &mut err) };
    assert!(!p.is_null(), "ratify_derive_id failed");
    let s = unsafe { CStr::from_ptr(p) }.to_str().unwrap().to_string();
    unsafe { ratify_string_free(p) };
    s
}

/// One fresh fixture key.
struct Key {
    name: &'static str,
    kp: Kp,
    public: RatifyV2PublicKey,
    id: String,
    ed_seed: [u8; 32],
    ml_seed: [u8; 32],
}

impl Key {
    fn fresh(name: &'static str) -> Key {
        let (kp, ed_seed, ml_seed) = Kp::generate();
        let public = kp.public();
        let id = kp.id();
        Key {
            name,
            kp,
            public,
            id,
            ed_seed,
            ml_seed,
        }
    }

    fn json(&self) -> Value {
        key_json(&self.public)
    }

    fn entry(&self) -> KeyEntry {
        KeyEntry {
            name: self.name.into(),
            ed25519_seed_hex: hex::encode(self.ed_seed),
            ml_dsa_65_seed_hex: hex::encode(self.ml_seed),
            public_key: BTreeMap::from([
                ("ed25519".to_string(), enc(&self.public.ed25519)),
                ("ml_dsa_65".to_string(), enc(&self.public.ml_dsa_65)),
            ]),
            key_id_v2: self.id.clone(),
            v1_key_id_128: v1_id(&self.public),
        }
    }
}

struct Keys(BTreeMap<&'static str, Key>);

