#!/usr/bin/env bash
# Build the Rust FFI layer for Android ABIs and the host, and generate the
# Kotlin bindings with every top-level declaration rewritten to `internal`.
#
#   sdks/kotlin/scripts/build-rust.sh              # all ABIs
#   ABIS="arm64-v8a" sdks/kotlin/scripts/build-rust.sh
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
ffi="$here/../ffi"
abis="${ABIS:-arm64-v8a armeabi-v7a x86_64}"
out="$here/ratify-protocol/build/rust/jniLibs"
gen="$here/ratify-protocol/src/main/kotlin/com/ratifyprotocol/internal/ffi"
# FEATURES=test-hooks builds the test-only panic hook in (local and CI test
# runs); release artifacts are built without it.
features="${FEATURES:-}"
export ANDROID_NDK_HOME="${ANDROID_NDK_HOME:-$HOME/Library/Android/sdk/ndk/28.2.13676358}"

rm -rf "$out"   # only this run's libraries are packaged and checked
targets=()
for a in $abis; do targets+=(-t "$a"); done
(cd "$ffi" && cargo ndk --platform 28 "${targets[@]}" -o "$out" build --lib --release ${features:+--features "$features"})

host_library="target/release/libratify_protocol_ffi.dylib"
if [ "$(uname -s)" = Linux ]; then host_library="target/release/libratify_protocol_ffi.so"; fi
(cd "$ffi" && cargo build --lib --release ${features:+--features "$features"} && \
  cargo run -q --features bindgen --bin uniffi-bindgen -- generate --no-format \
    --library "$host_library" \
    --language kotlin --out-dir "$here/build/gen")

mkdir -p "$gen"
{
  echo "// GENERATED by sdks/kotlin/scripts/build-rust.sh from sdks/ffi. Do not edit."
  echo "// Every top-level declaration is internal: the public API is hand-written."
  sed -E \
    -e 's/^public //' \
    -e 's/^((data|sealed|open|abstract|enum|inline|suspend|value|operator) )*(class|interface|object|fun|val|var|typealias) /internal &/' \
    -e 's/(^|[ \/])fun `ffi/\1internal fun `ffi/' \
    "$here/build/gen/com/ratifyprotocol/internal/ffi/ratify_ffi.kt" | sed -E 's/[[:blank:]]+$//'
} > "$gen/ratify_ffi.kt"

# Fail if a future UniFFI release emits a declaration form the rewrite misses:
# no explicit `public`, and no top-level declaration without a visibility.
code="$(grep -vE '^[[:space:]]*(//|\*|/\*)' "$gen/ratify_ffi.kt")"
if echo "$code" | grep -nE '(^|[^A-Za-z0-9_."`])public ' \
  || echo "$code" | grep -nE '^(@[A-Za-z.]+(\([^)]*\))? )*(data |sealed |open |abstract |enum |inline |suspend |value |operator )*(class|interface|object|fun|val|var|typealias|const) '; then
  echo "generated Kotlin still has a public or unqualified top-level declaration" >&2; exit 1
fi
# A byte search, not nm, so the check never depends on the host toolchain.
if [ -z "$features" ] && find "$out" -name '*.so' -exec env LC_ALL=C grep -a -l ratify_ffi_test_ {} + | grep -q .; then
  echo "release build contains a test-only hook" >&2; exit 1
fi
echo "built jniLibs ($abis${features:+, features $features}) and bindings"
