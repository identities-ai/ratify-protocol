#!/usr/bin/env bash
# Build the Rust FFI layer for Android ABIs and the host, and generate the
# Kotlin bindings with every top-level declaration rewritten to `internal`.
#
#   sdks/kotlin/scripts/build-rust.sh              # all ABIs
#   ABIS="arm64-v8a" sdks/kotlin/scripts/build-rust.sh
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
ffi="$here/../ffi"
abis="${ABIS:-arm64-v8a armeabi-v7a x86_64}"
out="$here/ratify-protocol/build/rust/jniLibs"
gen="$here/ratify-protocol/src/main/kotlin/com/ratifyprotocol/internal/ffi"
export ANDROID_NDK_HOME="${ANDROID_NDK_HOME:-$HOME/Library/Android/sdk/ndk/28.2.13676358}"

targets=()
for a in $abis; do targets+=(-t "$a"); done
(cd "$ffi" && cargo ndk --platform 28 "${targets[@]}" -o "$out" build --lib --release)

(cd "$ffi" && cargo build --lib --release && \
  cargo run -q --features bindgen --bin uniffi-bindgen -- generate --no-format \
    --library target/release/libratify_protocol_ffi.dylib --language kotlin --out-dir "$here/build/gen")

mkdir -p "$gen"
{
  echo "// GENERATED by sdks/kotlin/scripts/build-rust.sh from sdks/ffi. Do not edit."
  echo "// Every top-level declaration is internal: the public API is hand-written."
  sed -E \
    -e 's/^public (fun|object|class|interface|data class|sealed class|open class|enum class|val|var)/\1/' \
    -e 's/^(data class|sealed class|open class|abstract class|enum class|class|interface|object|fun|inline fun|val|var|typealias) /internal \1 /' \
    -e 's/(^|[ \/])fun `ffi/\1internal fun `ffi/' \
    "$here/build/gen/com/ratifyprotocol/internal/ffi/ratify_ffi.kt"
} > "$gen/ratify_ffi.kt"
echo "built jniLibs ($abis) and bindings"
