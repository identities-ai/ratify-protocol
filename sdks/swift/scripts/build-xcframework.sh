#!/usr/bin/env bash
# Build the Rust FFI layer for every Apple slice, generate the Swift bindings
# (rewritten to internal access), and assemble RatifyProtocolFFI.xcframework.
#
#   sdks/swift/scripts/build-xcframework.sh          # all slices
#   SLICES="macos ios-sim" sdks/swift/scripts/...     # a subset, for local work
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
ffi="$here/../ffi"
out="$here/build"
gen="$here/Sources/RatifyProtocol/Generated"
slices="${SLICES:-macos ios ios-sim}"
profile="${PROFILE:-release}"

export IPHONEOS_DEPLOYMENT_TARGET=17.0
export MACOSX_DEPLOYMENT_TARGET=14.0

build() { (cd "$ffi" && cargo build --lib --profile "$profile" --target "$1"); }
lib() { echo "$ffi/target/$1/$profile/libratify_protocol_ffi.a"; }

rm -rf "$out" && mkdir -p "$out/headers"
args=()
for s in $slices; do
  case "$s" in
    macos)
      build aarch64-apple-darwin; build x86_64-apple-darwin
      mkdir -p "$out/macos"
      lipo -create "$(lib aarch64-apple-darwin)" "$(lib x86_64-apple-darwin)" -output "$out/macos/libratify_protocol_ffi.a"
      args+=(-library "$out/macos/libratify_protocol_ffi.a" -headers "$out/headers") ;;
    ios)
      build aarch64-apple-ios
      args+=(-library "$(lib aarch64-apple-ios)" -headers "$out/headers") ;;
    ios-sim)
      build aarch64-apple-ios-sim; build x86_64-apple-ios
      mkdir -p "$out/ios-sim"
      lipo -create "$(lib aarch64-apple-ios-sim)" "$(lib x86_64-apple-ios)" -output "$out/ios-sim/libratify_protocol_ffi.a"
      args+=(-library "$out/ios-sim/libratify_protocol_ffi.a" -headers "$out/headers") ;;
    *) echo "unknown slice $s" >&2; exit 2 ;;
  esac
done

# Bindings come from the host build's metadata (identical for every slice).
(cd "$ffi" && cargo build --lib --profile "$profile" && \
  cargo run -q --features bindgen --bin uniffi-bindgen -- generate \
    --library "target/$profile/libratify_protocol_ffi.dylib" --language swift --out-dir "$out/gen")
cp "$out/gen/ratify_ffiFFI.h" "$out/headers/"
cp "$out/gen/ratify_ffiFFI.modulemap" "$out/headers/module.modulemap"

# Generated declarations are never public API: rewrite them to internal.
{
  echo "// GENERATED by sdks/swift/scripts/build-xcframework.sh from sdks/ffi. Do not edit."
  echo "// Access is rewritten to internal: the public API is the hand-written layer."
  sed -E -e 's/(^|[^A-Za-z0-9_.])open class /\1class /g' \
         -e 's/(^|[^A-Za-z0-9_.])open func /\1func /g' \
         -e 's/(^|[^A-Za-z0-9_.])public +/\1/g' \
         "$out/gen/ratify_ffi.swift"
} > "$gen/ratify_ffi.swift"

xcodebuild -create-xcframework "${args[@]}" -output "$out/RatifyProtocolFFI.xcframework" >/dev/null
echo "built $out/RatifyProtocolFFI.xcframework ($slices)"
