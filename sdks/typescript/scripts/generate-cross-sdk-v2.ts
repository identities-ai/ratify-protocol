interface Key {
  name: string;
  pair: HybridKeyPairV2;
  id: string;
  entry: Record<string, unknown>;
}

const b64 = (b: Uint8Array) => base64Encode(b);
const zero48 = () => new Uint8Array(48);

function sigRecord(field: string, code: number, signer: Key, signable: Uint8Array, sig: HybridSignature): Record<string, unknown> {
  const m = v2SigningMessage(code, signable);
  const ctx = v2MLDSAContext(code);
  const tr = shake256(signer.pair.publicKey.ml_dsa_65, { dkLen: 64 });
  const mu = shake256(concatBytes(tr, new Uint8Array([0, ctx.length]), ctx, m), { dkLen: 64 });
  return {
    field, object_type_code: code, signer: signer.name, signer_key_id_v2: signer.id,
    signable_b64: b64(signable), signable_sha384_hex: hexOf(sha384(signable)), message_b64: b64(m),
    mldsa_context: new TextDecoder().decode(ctx), mldsa_tr_b64: b64(tr), mldsa_mu_b64: b64(mu),
    signature: { ed25519: b64(sig.ed25519), ml_dsa_65: b64(sig.ml_dsa_65) },
  };
}

async function newKey(name: string): Promise<Key> {
  const edSeed = globalThis.crypto.getRandomValues(new Uint8Array(32));
  const mlSeed = globalThis.crypto.getRandomValues(new Uint8Array(32));
  const { publicKey, privateKey } = await hybridKeypairFromSeeds(edSeed, mlSeed);
  const id = deriveKeyIDV2(publicKey);
  return {
    name, pair: { publicKey, privateKey }, id,
    entry: {
      name, ed25519_seed_hex: hexOf(edSeed), ml_dsa_65_seed_hex: hexOf(mlSeed),
      public_key: { ed25519: b64(publicKey.ed25519), ml_dsa_65: b64(publicKey.ml_dsa_65) }, key_id_v2: id, v1_key_id_128: deriveID(publicKey),
    },
  };
}

