test("tzdb: version is pinned to 2025c", () => {
  assert.equal(TZDB_VERSION_V2, "2025c");
});

test("tzdb: lookups equal the Go reference time package", () => {
  assert.ok(GO_REFERENCE.length > 400);
  for (const [zone, t, offset, end] of GO_REFERENCE) {
    const got = loadTZDBZoneV2(zone).lookup(t);
    assert.equal(got.offset, offset, `${zone} @ ${t} offset`);
    assert.equal(got.end === null ? -1 : got.end, end, `${zone} @ ${t} period end`);
  }
});

test("tzdb: known offsets and transitions", () => {
  const ny = loadTZDBZoneV2("America/New_York");
  // 2026-03-08 07:00 UTC is 03:00 EDT: DST starts at that exact instant.
  assert.deepEqual(ny.lookup(1772953199), { offset: -18000, end: 1772953200 });
  assert.equal(ny.lookup(1772953200).offset, -14400);
  assert.equal(loadTZDBZoneV2("Asia/Kolkata").lookup(1800000000).offset, 19800);
  assert.equal(loadTZDBZoneV2("Europe/London").lookup(1785000000).offset, 3600); // summer 2026
  assert.equal(loadTZDBZoneV2("Europe/London").lookup(1800000000).offset, 0); // January 2027
  const lordHowe = loadTZDBZoneV2("Australia/Lord_Howe");
  assert.equal(lordHowe.lookup(1785000000).offset, 37800); // +10:30 standard (July)
  assert.equal(lordHowe.lookup(1800000000).offset, 39600); // +11:00 half-hour DST (January)
  assert.deepEqual(loadTZDBZoneV2("UTC").lookup(253402300799), { offset: 0, end: null });
  // A year-9999 instant past every explicit transition uses the TZ footer rule.
  assert.equal(ny.lookup(253402300799).offset, -18000);
});

test("tzdb: unknown, Local, and empty zones are rejected; version is checked", () => {
  assert.throws(() => loadTZDBZoneV2("Local"));
  assert.throws(() => loadTZDBZoneV2(""));
  assert.throws(() => loadTZDBZoneV2("Mars/Olympus_Mons"));
  assert.throws(() => loadTZDBZoneV2("America/new_york"));
  assert.throws(() => loadV2TimeZone("", "UTC"), /no tzdb_version/);
  assert.throws(() => loadV2TimeZone("2025b", "UTC"), /differs/);
  assert.equal(loadV2TimeZone("2025c", "UTC").name, "UTC");
});
